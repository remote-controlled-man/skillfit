import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {existsSync,mkdirSync,mkdtempSync,readFileSync,renameSync,rmSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

// Argument 1: an extracted or registry-installed skillfit package. Argument 2:
// a fresh parent directory for synthetic data and the resulting JSON receipt.
const installed=resolve(process.argv[2]), parent=resolve(process.argv[3]);
mkdirSync(parent,{recursive:true});
const root=mkdtempSync(join(parent,'case-smoke-')), bench=join(root,'bench'), skill=join(root,'skill');
const load=path=>import(pathToFileURL(join(installed,'dist',path)).href);
const {runBenchInit}=await load('commands/bench.js');
const {runEval}=await load('commands/eval.js');
const {exportEvaluation}=await load('commands/eval-export.js');
const {MockExecutor}=await load('harness/executors/mock.js');
const cli=(...args)=>{
 const child=spawnSync(process.execPath,[join(installed,'dist/cli.js'),...args],{cwd:root,encoding:'utf8',timeout:60_000,maxBuffer:16*1024*1024});
 assert.equal(child.status,0,child.stderr||child.stdout); return child.stdout;
};
const checks={};
assert.equal(cli('--version').trim(),'0.10.0'); checks.version=true;
const help=cli('--help'); for(const flag of ['--export','--input-root','bench list','bench remove','--task']) assert.ok(help.includes(flag)); checks.help=true;
await runBenchInit({dir:bench,yes:true,log:()=>{}});
const manifestPath=join(bench,'bench.json'), initial=JSON.parse(readFileSync(manifestPath));
initial.tasks.push({...initial.tasks[0],id:'second-case'}); writeFileSync(manifestPath,JSON.stringify(initial));
assert.equal(JSON.parse(cli('bench','list',bench,'--json')).tasks.length,2);
assert.equal(JSON.parse(cli('bench','show',bench,'second-case','--json')).tasks[0].id,'second-case'); checks.listShow=true;
const before=readFileSync(manifestPath,'utf8');
assert.equal(JSON.parse(cli('bench','edit',bench,'second-case','--set','shouldTrigger=false','--json')).status,'planned');
assert.equal(readFileSync(manifestPath,'utf8'),before);
assert.equal(JSON.parse(cli('bench','edit',bench,'second-case','--set','shouldTrigger=false','--yes','--json')).status,'applied');
assert.equal(readFileSync(manifestPath+'.skillfit-bak','utf8'),before); checks.editPlanBackup=true;
assert.equal(JSON.parse(cli('bench','remove',bench,'second-case','--yes','--json')).status,'applied');
assert.ok(existsSync(join(bench,initial.tasks[0].prompt))); checks.removePreservesFiles=true;
const health=JSON.parse(cli('bench','check',bench,'--json')); assert.ok(Array.isArray(health.checks)); checks.benchCheckJson=true;
mkdirSync(skill); writeFileSync(join(skill,'SKILL.md'),'# Synthetic publication smoke\n');
const mock=new MockExecutor(); let syntheticCalls=0;
const executor={describe:()=>mock.describe(),run:async(...args)=>{syntheticCalls++;return mock.run(...args)}};
const options={skillPath:skill,bench,taskIds:['example-task'],trials:1,maxCalls:2,executor,judgeExecutor:null,yes:true,runsRoot:join(root,'runs'),runGroup:'synthetic',log:()=>{}};
await runEval({...options,dryRun:true,onPlan:p=>{assert.equal(p.plannedCalls,2);assert.deepEqual(p.bench.taskIds,['example-task']);}});
assert.equal(syntheticCalls,0); checks.selectedPreviewNoCalls=true;
await runEval({...options,dryRun:false}); assert.equal(syntheticCalls,2);
const run=join(root,'runs/synthetic'), output=join(root,'export');
const original=JSON.parse(cli('report','eval',run,'--json'));
const plan=JSON.parse(cli('report','eval',run,'--export',output,'--json')); assert.equal(plan.status,'planned'); assert.ok(!existsSync(output)); checks.exportPlan=true;
await exportEvaluation(run,output,{yes:true,log:()=>{}});
const moved=join(root,'moved package'); renameSync(output,moved);
for(const path of [bench,skill,join(root,'runs')]) rmSync(path,{recursive:true});
const reproduce=verify=>{
 const child=spawnSync(process.execPath,[join(moved,'reproduce.mjs'),...(verify?['--verify-only']:[])],{cwd:root,encoding:'utf8',timeout:60_000,maxBuffer:16*1024*1024});
 assert.equal(child.status,0,child.stderr); return JSON.parse(child.stdout);
};
assert.equal(reproduce(true).verified,true); checks.portableChecksums=true;
const replay=reproduce(false); assert.equal(replay.evidence.verified,true); assert.deepEqual(replay.costs,original.costs);
assert.equal(replay.acceptance.eligibleForUpgrade,false); assert.equal(replay.acceptance.automaticUpgrade,false);
const inspected=JSON.parse(cli('report','eval',moved,'--json','--replay')); assert.equal(inspected.portablePackage.integrityVerified,true);
assert.equal(syntheticCalls,2); checks.movedPackageReplayWithoutOriginals=true; checks.exactCosts=true;
const receipt={schemaVersion:1,kind:'skillfit.release-case-workflow-smoke',version:'0.10.0',verifiedAt:new Date().toISOString(),modelCalls:0,agentCliCalls:0,syntheticExecutorCalls:syntheticCalls,checks};
writeFileSync(join(parent,'feature-smoke.json'),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
rmSync(root,{recursive:true});
console.log(JSON.stringify(receipt));
